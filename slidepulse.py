def ps_quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def groovy_quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r")
    return "'" + escaped + "'"


def groovy_list(values) -> str:
    return "[" + ", ".join(groovy_quote(v) for v in values) + "]"


def gui_python() -> str:
    exe = Path(sys.executable)
    if os.name == "nt" and exe.with_name("pythonw.exe").is_file():
        return str(exe.with_name("pythonw.exe"))
    return str(exe)


def copilot_hooks_json() -> str:
    hooks = {}
    for hook in COPILOT_HOOKS:
        args = [sys.executable, "-I", str(SCRIPT), "copilot", hook]
        entry = {"type": "command",
                 "bash": " ".join(shlex.quote(a) for a in args),
                 "powershell": "& " + " ".join(ps_quote(a) for a in args),
                 "timeoutSec": 5}
        if hook == "notification":
            entry["matcher"] = COPILOT_INPUT_TYPES
        hooks[hook] = [entry]
    return json.dumps({"version": 1, "hooks": hooks}, indent=2) + "\n"


def render_template(name: str, **values: str) -> str:
    text = (HERE / "integrations" / name).read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    if "{{" in text:
        raise ValueError(f"unfilled placeholder in {name}")
    return text


def studio_config_dir() -> Path | None:
    if os.name == "nt":
        base = Path(os.environ.get("APPDATA") or Path.home() / "AppData" / "Roaming") / "Google"
    elif sys.platform == "darwin":
        base = Path.home() / "Library" / "Application Support" / "Google"
    else:
        base = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "Google"

    def version(path: Path):
        return tuple(int(n) for n in re.findall(r"\d+", path.name))

    dirs = [d for d in base.glob("AndroidStudio*") if d.is_dir() and "Preview" not in d.name]
    return max(dirs, key=version) if dirs else None


def integration_files(studio_dir: Path | None) -> list:
    """(label, destination, content) for every file `install` writes."""
    copilot_home = Path(os.environ.get("COPILOT_HOME") or Path.home() / ".copilot")
    gradle_home = Path(os.environ.get("GRADLE_USER_HOME") or Path.home() / ".gradle")
    build_hook = gradle_home / "slidepulse" / "build-done.gradle"
    files = [
        ("Copilot CLI hooks", copilot_home / "hooks" / "slidepulse.json", copilot_hooks_json()),
        ("Gradle init script", gradle_home / "init.d" / "slidepulse.gradle",
         render_template("gradle-init.gradle", HOOK=groovy_quote(str(build_hook)))),
        ("Gradle build hook", build_hook,
         render_template("gradle-build-done.gradle",
                         COMMAND=groovy_list([gui_python(), "-I", str(SCRIPT), "event"]))),
    ]
    if studio_dir:
        files.append(("Android Studio startup script",
                      studio_dir / "extensions" / "com.intellij" / "startup" / "slidepulse.groovy",
                      render_template("android-studio.groovy",
                                      COMMAND=groovy_list([gui_python(), "-I", str(SCRIPT)]))))
    return files


def _ours(path: Path) -> bool:
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return MARKER in text or (path.suffix == ".json" and SCRIPT.name in text)


def install(dry_run: bool, studio: str | None) -> int:
    if sys.version_info < (3, 9):
        warn("Python 3.9 or newer is required")
        return 1
    studio_dir = Path(studio) if studio else studio_config_dir()
    status = 0
    for label, dest, content in integration_files(studio_dir):
        if dest.exists() and not _ours(dest):
            warn(f"{dest} exists and was not written by slidepulse; left unchanged")
            status = 1
            continue
        print(f"{'would write' if dry_run else 'wrote'} {label}: {dest}")
        if not dry_run:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content, encoding="utf-8")
    if not studio_dir:
        warn("no Android Studio settings folder found; pass --studio-dir to add the IDE bridge")
    if not dry_run:
        print("\nNext: restart Android Studio, start a new Copilot CLI session, "
              "then run `slidepulse.py demo` with the light plugged in.")
    return status


def uninstall(studio: str | None) -> int:
    studio_dir = Path(studio) if studio else studio_config_dir()
    for label, dest, _ in integration_files(studio_dir):
        if dest.exists() and _ours(dest):
            dest.unlink()
            print(f"removed {label}: {dest}")
    stop_agent()
    return 0


