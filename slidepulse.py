def cmd_status(cfg: dict) -> int:
    led = find_device(cfg)
    print(f"slidepulse {VERSION}")
    print(f"device:  {led or 'not found'}")
    pid_file = state_dir() / "agent.pid"
    pid = pid_file.read_text(encoding="ascii").strip() if pid_file.is_file() else "?"
    print(f"agent:   {f'running (pid {pid})' if agent_running() else 'stopped'}")
    with locked_state() as state:
        _desired(state, cfg, time.time())
        now = time.time()
        held = ", ".join(f"{n} ({int(t - now)} s left)" for n, t in state["held"].items()) or "none"
        print(f"showing: {state['shown'] or 'unknown'}")
        print(f"held:    {held}")
    print(f"adb:     {find_adb(cfg) or 'not found'}")
    print(f"config:  {CONFIG_PATH if CONFIG_PATH.is_file() else 'defaults (no config.json)'}")
    print(f"state:   {state_dir()}")
    return 0


def cmd_demo(cfg: dict) -> int:
    if find_device(cfg) is None:
        warn("no device found; plug it in or set SLIDEPULSE_DEVICE")
        return 1
    steps = [("event", "copilot-done", 3), ("event", "copilot-input", 4), ("clear", "copilot-input", 1),
             ("event", "build-ok", 3), ("event", "build-failed", 3), ("event", "installed", 3),
             ("event", "crash", 4),
             ("clear", "crash", 1), ("event", "breakpoint", 4), ("clear", "all", 0)]
    for action, name, pause in steps:
        print(f"{action} {name}")
        apply(action, name, cfg)
        time.sleep(pause)
    return 0


def cmd_write(cfg: dict, program: str) -> int:
    program = program.replace("\\n", "\n")
    validate(program)
    led = find_device(cfg)
    if led is None:
        warn("no device found")
        return 1
    with locked_state() as state:
        write_program(led, program)
        state["shown"] = _desired(state, cfg, time.time())[0]  # keep it until the state changes
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="slidepulse", description=__doc__.split("\n\n")[0])
    parser.add_argument("--version", action="version", version=VERSION)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("event", help="trigger an event").add_argument("name", choices=list(EVENTS))
    sub.add_parser("clear", help="end a held state").add_argument("name", choices=HOLDS + ["all"])
    sub.add_parser("copilot", help="entry point for Copilot CLI hooks").add_argument("hook")
    sub.add_parser("write", help="write a raw LED program").add_argument("program")
    sub.add_parser("off", help="clear everything and switch the LEDs off")
    sub.add_parser("status", help="show device, agent and active states")
    sub.add_parser("demo", help="play every effect once")
    sub.add_parser("agent", help="run the background agent in the foreground")
    sub.add_parser("start", help="start the background agent if it is not running")
    sub.add_parser("stop", help="stop the background agent")
    for name in ("install", "uninstall"):
        p = sub.add_parser(name, help=f"{name} the Copilot, Gradle and Android Studio integrations")
        p.add_argument("--studio-dir", help="Android Studio settings folder (default: newest found)")
        if name == "install":
            p.add_argument("--dry-run", action="store_true", help="only print what would be written")
    args = parser.parse_args(argv)
    cfg = load_config()

    try:
        if args.command in ("event", "clear", "copilot"):
            if args.command == "copilot":
                if args.hook not in COPILOT_HOOKS:
                    return 0  # unknown hooks are ignored so Copilot never sees a failure
                action, name = COPILOT_HOOKS[args.hook]
            else:
                action, name = args.command, args.name
            result = apply(action, name, cfg)
            if result == "no device":
                warn("no device found; the state is kept and shown once it is plugged in")
            ensure_agent(cfg)
            return 0
        if args.command == "off":
            with locked_state() as state:
                state["held"], state["flash"] = {}, None
                if render(state, cfg, time.time(), force=True) == "no device":
                    warn("no device found")
            return 0
        if args.command == "write":
            return cmd_write(cfg, args.program)
        if args.command == "status":
            return cmd_status(cfg)
        if args.command == "demo":
            return cmd_demo(cfg)
        if args.command == "agent":
            return run_agent(cfg)
        if args.command == "start":
            ensure_agent(cfg)
            return 0
        if args.command == "stop":
            return 0 if stop_agent() else 1
        if args.command == "install":
            return install(args.dry_run, args.studio_dir)
        if args.command == "uninstall":
            return uninstall(args.studio_dir)
    except (OSError, ValueError, TimeoutError) as exc:
        warn(str(exc))
        # Hooks must never break Copilot, Gradle or the IDE: events always exit 0.
        return 0 if args.command in ("event", "clear", "copilot") else 1
    return 2


if __name__ == "__main__":
    sys.exit(main())
